import assert from "node:assert/strict";
import fs from "node:fs";
import { createServer } from "vite";
const server = await createServer({ server: { middlewareMode: true }, appType: "custom" });
const previousLocation = globalThis.location;
try {
  const { WORKSPACE_KEY, readWorkspace, writeWorkspace, withPracticeReport } = await server.ssrLoadModule("/src/offlineStorage.ts");
  const { status } = await server.ssrLoadModule("/src/types.ts");
  const { parseReport } = await server.ssrLoadModule("/src/reports.ts");
  const storage = new Map();
  const local = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value), removeItem: key => storage.delete(key) };
  const problem = { id: "rl/gae", starter: "# starter\n", tests: { T0: 1 } };
  const report = { problem: problem.id, summary: { T0: [1, 1] }, tests: [{ id: "test_core", layer: "T0", passed: true }] };
  const code = 'def 解法():\r\n\treturn "🧪"\r\n';
  assert.deepEqual(readWorkspace(local), { records: {}, error: false });
  let records = { [problem.id]: { code }, "architecture/attention": { code: "another module" } };
  assert(writeWorkspace(local, records));
  records = readWorkspace(local).records;
  assert.equal(records[problem.id].code, code, "Refreshing must recover exact Unicode source and line endings");
  records[problem.id] = withPracticeReport(records[problem.id], problem, report);
  assert(writeWorkspace(local, records));
  let fresh = readWorkspace(local).records;
  assert.equal(status(problem, fresh[problem.id]), "done");
  const failed = { ...report, tests: [{ ...report.tests[0], passed: false }], summary: { T0: [0, 1] } };
  const editedDuringRun = { ...fresh[problem.id], code: "new source while Python runs" };
  fresh[problem.id] = withPracticeReport(editedDuringRun, problem, failed);
  assert.equal(fresh[problem.id].code, editedDuringRun.code, "Late reports cannot replace newer editor source");
  assert(writeWorkspace(local, fresh));
  assert.equal(status(problem, readWorkspace(local).records[problem.id]), "done", "A later failure cannot erase completion");
  fresh[problem.id] = { ...fresh[problem.id], code: problem.starter };
  assert(writeWorkspace(local, fresh));
  assert.equal(status(problem, readWorkspace(local).records[problem.id]), "done", "Restoring the starter preserves completion");
  assert.equal(readWorkspace(local).records["architecture/attention"].code, "another module");
  const before = storage.get(WORKSPACE_KEY);
  const blocked = { ...local, setItem() { throw new DOMException("full", "QuotaExceededError"); } };
  const unsaved = { ...fresh, [problem.id]: { code: "not lost from memory" } };
  assert.equal(writeWorkspace(blocked, unsaved), false, "Storage failures must be explicit");
  assert.equal(unsaved[problem.id].code, "not lost from memory");
  assert.equal(storage.get(WORKSPACE_KEY), before, "A failed save must not remove the previous durable draft");
  assert(writeWorkspace(local, unsaved), "Retry can save the preserved draft");
  storage.set(WORKSPACE_KEY, "{broken");
  assert(readWorkspace(local).error);
  assert.equal(storage.get(WORKSPACE_KEY), "{broken", "Reading corrupt storage must not clear it");
  assert(readWorkspace({ getItem() { throw Error("denied"); } }).error);
  assert.equal(withPracticeReport(editedDuringRun, problem, { ...report, problem: "rl/ppo" }), editedDuringRun);
  const preserved = parseReport({ ...report, workspace_preserved: true, workspace_warning: "changed", source_path: "solutions/gae.py" });
  assert.equal(preserved.workspace_preserved, true);
  assert.equal(preserved.source_path, "solutions/gae.py");
  assert.throws(() => parseReport({ ...report, workspace_preserved: "yes" }));
  console.log("PASS offline source recovery, report persistence, completion retention, late-run edits and explicit storage failures");

  const { CLIENT_KEY, PENDING_KEY, clientId, rememberRun, recallRun } = await server.ssrLoadModule("/src/judgeSession.ts");
  const client = clientId(local);
  assert.match(client, /^[a-f0-9]{32}$/);
  assert.equal(clientId(local), client, "A reload keeps the local queue owner");
  const id = "a".repeat(32);
  rememberRun(local, { id, problem: problem.id });
  assert.deepEqual(recallRun(local), { id, problem: problem.id }, "A reload reattaches to the exact run");
  rememberRun(local);
  assert.equal(recallRun(local), undefined);
  assert.equal(storage.get(CLIENT_KEY), client);
  storage.set(PENDING_KEY, JSON.stringify({ id: "not-an-id", problem: problem.id }));
  assert.equal(recallRun(local), undefined);
  console.log("PASS pending-run recovery and stable local client identity without accounts");

  const { isLocalOrigin, localRequest, LocalRequestError } = await server.ssrLoadModule("/src/localApi.ts");
  for (const origin of ["http://localhost:5173", "http://127.0.0.1:8765", "http://[::1]:8765"]) assert(isLocalOrigin(origin));
  for (const origin of ["https://example.com", "http://localhost.example.com", "http://192.168.1.2", "file:///tmp/index.html", "http://user@localhost"]) assert(!isLocalOrigin(origin));
  let calls = 0;
  const fetcher = async (_url, init) => { calls++; assert.equal(init.redirect, "error"); assert.equal(init.credentials, "omit"); return Response.json({ ok: true }); };
  globalThis.location = { origin: "https://example.com" };
  await assert.rejects(localRequest("/api/judge/jobs", { method: "POST", body: JSON.stringify({ code: "private source" }) }, fetcher), LocalRequestError);
  assert.equal(calls, 0, "An accidentally hosted build must never upload source");
  globalThis.location = { origin: "http://127.0.0.1:5173" };
  for (const path of ["https://example.com/api/judge/jobs", "//example.com/api/health", "/api/account/me", "/api/../external", "/api/judge/jobs/../../anything"])
    await assert.rejects(localRequest(path, {}, fetcher), LocalRequestError);
  assert.equal(calls, 0);
  await localRequest("/api/health", {}, fetcher);
  await localRequest("/api/workspace?problem=rl%2Fgae", {}, fetcher);
  assert.equal(calls, 2);
  const { parseJob, requestJob, watchJob } = await server.ssrLoadModule("/src/judgeJobs.ts");
  const baseJob = { id, problem: problem.id, status: "queued", ahead: 0 };
  const controller = new AbortController();
  let submitted = 0;
  await requestJob("", client, controller.signal, { id, problem: problem.id, code }, async (path, init) => {
    assert.equal(path, "/api/judge/jobs"); assert.equal(init.method, "POST");
    assert.equal(init.headers["X-PaperLeet-Client-ID"], client);
    assert.equal(JSON.parse(init.body).code, code); assert.equal(init.redirect, "error");
    submitted++; return Response.json(baseJob);
  });
  const responses = [new TypeError("network interrupted"), baseJob, { ...baseJob, status: "running" }, { ...baseJob, status: "succeeded", report }];
  const states = [], connections = [], delays = [];
  const result = await watchJob(id, client, controller.signal, value => states.push(value.status), value => connections.push(value), async (_path, init) => {
    assert.equal(init.method, "GET", "Reconnect only polls; it never executes again");
    const next = responses.shift(); if (next instanceof Error) throw next; return Response.json(next);
  }, async ms => { delays.push(ms); });
  assert.equal(result.status, "succeeded"); assert.equal(submitted, 1);
  assert.deepEqual(states, ["queued", "running", "succeeded"]);
  assert.deepEqual(connections, [false, true, true, true]); assert.deepEqual(delays, [2000, 1000, 1000]);
  await assert.rejects(watchJob(id, client, controller.signal, () => {}, () => {}, async () => Response.json({ error: "expired" }, { status: 404 }), async () => {}), error => error.status === 404);
  await assert.rejects(watchJob(id, client, controller.signal, () => {}, () => {}, async () => Response.json({ ...baseJob, id: "b".repeat(32) }), async () => {}), error => error.status === 422);
  assert.throws(() => parseJob({ ...baseJob, status: "succeeded" }));
  assert.throws(() => parseJob({ ...baseJob, status: "succeeded", report: { ...report, problem: "rl/ppo" } }));
  assert.throws(() => parseJob({ ...baseJob, ahead: -1 }));
  console.log("PASS loopback-only API boundaries, exact source handoff, redirect protection, interrupted-run recovery and validated native reports");
  const app = fs.readFileSync("src/App.tsx", "utf8");
  for (const removed of ["Account.tsx", "Community.tsx", "Submissions.tsx", "social.tsx", "OnlinePresence.tsx", "ProblemStats.tsx"])
    assert(!fs.existsSync(`src/${removed}`), `${removed} must be absent`);
  assert(!/Globe2|theme-label|setGuide|Code backup|BrowserDraft/.test(app));
  assert.match(app, /workspace_preserved/);
  assert(fs.readFileSync("index.html", "utf8").includes("connect-src 'self'"));
} finally {
  if (previousLocation === undefined) delete globalThis.location; else globalThis.location = previousLocation;
  await server.close();
}
